import { test } from "node:test";
import assert from "node:assert/strict";
import { SlackApp, ThreadQueue } from "./index.js";
import { config } from "../config/index.js";
import { FIXTURE } from "../agent/postmortem/fixtures.js";

// `@agent postmortem` wiring (spec 2026-10-14-postmortem-draft-design.md §1 Trigger, §6 Config,
// Error handling table). Fake-`this` pattern from resolved-early.test.ts.

// config is `as const` for the TYPE system only — nothing freezes it at runtime (see
// dashboard/server.test.ts) — so the public-URL link can be exercised without an env var set
// before this file's static imports evaluated config. Restored in a finally so it never leaks
// into another test file sharing this process.
const dashboardConfig = config.dashboard as unknown as { publicUrl?: string };

const FULL_MD = [
  "# Postmortem draft — HighErrorRate in sample-apps (incident #7)",
  "",
  "_Resolved. Draft generated by the DevOps AI agent at 2026-10-14T00:00:00.000Z; review before sharing._",
  "",
  "## Summary",
  "Everything broke because of pool exhaustion.",
  "",
  "## Impact",
  "Checkout was unavailable for 12 minutes.",
  "",
  "## Root cause",
  "Not confirmed by a human; the agent's hypothesis was: connection pool exhaustion.",
  "",
  "## What went well",
  "The alert fired quickly.",
  "",
  "## What went poorly",
  "No runbook existed.",
  "",
  "## Action items",
  "- increase pool size _(draft — needs an owner)_",
  "",
  "## Sources",
  "Read: incident row",
].join("\n");

interface Overrides {
  incidentId?: number | null;
  facts?: unknown;
  draftThrows?: string;
  draft?: { markdown: string; backend: string };
  storedId?: number | null;
  messages?: Array<{ ts?: string; user?: string; bot_id?: string; text?: string }>;
  repliesThrows?: string;
  repliesPages?: Array<{ messages: Array<{ ts?: string; user?: string; bot_id?: string; text?: string }>; next_cursor?: string }>;
}

const FACTS = FIXTURE;

function harness(overrides: Overrides = {}) {
  const posted: any[] = [];
  const updated: any[] = [];
  const calls = { facts: [] as any[], draftCount: 0, draftArgs: [] as any[], store: [] as any[] };

  const inFlightCalls: any[] = [];
  const self: any = {
    threadQueue: new ThreadQueue(),
    inFlight: { track: (key: any, p: Promise<unknown>) => { inFlightCalls.push(key); return p; } },
    agent: {
      findIncidentForThread: async () => (overrides.incidentId === undefined ? null : overrides.incidentId),
      postmortemFacts: async (id: number, humans: string[] | null) => {
        calls.facts.push({ id, humans });
        return overrides.facts === undefined ? FACTS : overrides.facts;
      },
      draftPostmortem: async (_f: unknown, threadId?: string) => {
        calls.draftCount++;
        calls.draftArgs.push(threadId);
        if (overrides.draftThrows) throw new Error(overrides.draftThrows);
        return overrides.draft ?? { markdown: FULL_MD, backend: "claude" };
      },
      storePostmortem: async (id: number, by: string | null, markdown: string, backend: string) => {
        calls.store.push({ id, by, markdown, backend });
        return overrides.storedId === undefined ? 99 : overrides.storedId;
      },
    },
  };

  const client: any = {
    chat: {
      postMessage: async (m: any) => {
        posted.push(m);
        return { ts: `p${posted.length}` };
      },
      update: async (m: any) => {
        updated.push(m);
      },
    },
    conversations: {
      // repliesPages[0]'s own next_cursor is the literal cursor value the fake hands back and
      // expects on the next call — page index doesn't matter, only that the cursor is threaded.
      replies: async (args: { cursor?: string }) => {
        if (overrides.repliesThrows) throw new Error(overrides.repliesThrows);
        if (overrides.repliesPages) {
          const idx = args.cursor ? overrides.repliesPages.findIndex((p) => p.next_cursor === args.cursor) + 1 : 0;
          const page = overrides.repliesPages[idx];
          return { messages: page.messages, response_metadata: page.next_cursor ? { next_cursor: page.next_cursor } : undefined };
        }
        return { messages: overrides.messages ?? [] };
      },
    },
  };

  const run = (event: { channel: string; ts: string; thread_ts?: string; user?: string }) => {
    const threadId = event.thread_ts ?? event.ts;
    return (SlackApp.prototype as any).handlePostmortem.call(self, event, client, threadId);
  };

  return { self, client, posted, updated, calls, run, inFlightCalls };
}

test("no top-level incident for this thread: one refusal line, draftPostmortem never called", async () => {
  const h = harness({ incidentId: null });
  await h.run({ channel: "C1", ts: "100.9", thread_ts: "100.0", user: "U1" });

  assert.equal(h.posted.length, 1);
  assert.match(h.posted[0].text, /not an incident thread/i);
  assert.equal(h.posted[0].thread_ts, "100.0");
  assert.equal(h.calls.draftCount, 0);
  assert.equal(h.calls.store.length, 0);
});

test("an incident thread: humans from the human message only, draft stored, summary posted with the public-URL link", async () => {
  const prev = dashboardConfig.publicUrl;
  dashboardConfig.publicUrl = "https://dash.example";
  try {
    const h = harness({
      incidentId: 7,
      messages: [
        { ts: "100.1", user: "U1", text: "connection pool exhausted causing errors" },
        { ts: "100.2", bot_id: "B1", text: "Investigating now, give me a second please" },
      ],
    });
    await h.run({ channel: "C1", ts: "100.9", thread_ts: "100.0", user: "U1" });

    assert.deepEqual(h.calls.facts, [{ id: 7, humans: ["connection pool exhausted causing errors"] }]);
    assert.equal(h.calls.store.length, 1);
    assert.equal(h.calls.store[0].id, 7);
    assert.equal(h.calls.store[0].by, "U1");
    assert.equal(h.calls.store[0].markdown, FULL_MD);

    // progress line posted then edited in place
    assert.equal(h.posted[0].text, "📝 Drafting the postmortem…");
    assert.equal(h.updated.length, 1);
    assert.equal(h.updated[0].ts, "p1");
    assert.match(h.updated[0].text, /https:\/\/dash\.example\/incidents\/7\/postmortem/);

    const final = h.posted[h.posted.length - 1].text;
    assert.match(final, /\*⚡ Summary\*/);
    assert.match(final, /Everything broke because of pool exhaustion\./);
    assert.match(final, /\*🔧 Action items\*/);
    assert.match(final, /<https:\/\/dash\.example\/incidents\/7\/postmortem\|Full draft on the dashboard>/);
    assert.match(final, /increase pool size/);
    assert.doesNotMatch(final, /not stored/);
  } finally {
    dashboardConfig.publicUrl = prev;
  }
});

test("without DASHBOARD_PUBLIC_URL the posted link is the bare path", async () => {
  const prev = dashboardConfig.publicUrl;
  dashboardConfig.publicUrl = undefined;
  try {
    const h = harness({ incidentId: 7 });
    await h.run({ channel: "C1", ts: "100.9", thread_ts: "100.0", user: "U1" });
    assert.match(h.updated[0].text, /(?<!\/)\/incidents\/7\/postmortem/);
    assert.doesNotMatch(h.updated[0].text, /https?:\/\//);
  } finally {
    dashboardConfig.publicUrl = prev;
  }
});

test("draftPostmortem throws: progress edited to the error, nothing stored", async () => {
  const h = harness({ incidentId: 7, draftThrows: "LLM timeout" });
  await h.run({ channel: "C1", ts: "100.9", thread_ts: "100.0", user: "U1" });

  assert.equal(h.updated.length, 1);
  assert.match(h.updated[0].text, /Could not draft the postmortem/);
  assert.match(h.updated[0].text, /LLM timeout/);
  assert.equal(h.calls.store.length, 0);
});

test("postmortemFacts returns null (incident row unreadable): treated like a draft error, no LLM call, nothing stored", async () => {
  const h = harness({ incidentId: 7, facts: null });
  await h.run({ channel: "C1", ts: "100.9", thread_ts: "100.0", user: "U1" });

  assert.equal(h.updated.length, 1);
  assert.match(h.updated[0].text, /Could not draft the postmortem/);
  assert.equal(h.calls.draftCount, 0);
  assert.equal(h.calls.store.length, 0);
});

test("storePostmortem returns null: summary still posted, with a not-stored note", async () => {
  const h = harness({ incidentId: 7, storedId: null });
  await h.run({ channel: "C1", ts: "100.9", thread_ts: "100.0", user: "U1" });

  assert.equal(h.calls.store.length, 1);
  const final = h.posted[h.posted.length - 1].text;
  assert.match(final, /\*⚡ Summary\*/);
  assert.match(final, /not stored/);

  assert.equal(h.updated[0].text, "📝 Postmortem drafted — not stored (the dashboard will not have it)");
  assert.doesNotMatch(h.updated[0].text, /https?:\/\//);
  assert.doesNotMatch(h.updated[0].text, /\/incidents\//);
});

test("draftPostmortem is called with the Slack thread id, for usage attribution", async () => {
  const h = harness({ incidentId: 7 });
  await h.run({ channel: "C1", ts: "100.9", thread_ts: "100.0", user: "U1" });

  assert.deepEqual(h.calls.draftArgs, ["100.0"]);
});

test("a postmortem run is tracked in InFlightWork like a mention, for shutdown drain", async () => {
  const h = harness({ incidentId: 7 });
  await h.run({ channel: "C1", ts: "100.9", thread_ts: "100.0", user: "U1" });

  assert.deepEqual(h.inFlightCalls, [{ channel: "C1", threadTs: "100.0", kind: "mention" }]);
});

test("conversations.replies is paginated: humans from both pages reach postmortemFacts", async () => {
  const h = harness({
    incidentId: 7,
    repliesPages: [
      { messages: [{ ts: "100.1", user: "U1", text: "connection pool exhausted causing errors" }], next_cursor: "cursor1" },
      { messages: [{ ts: "100.2", user: "U2", text: "it started after the timeout change deployed" }] },
    ],
  });
  await h.run({ channel: "C1", ts: "100.9", thread_ts: "100.0", user: "U1" });

  assert.deepEqual(h.calls.facts[0].humans, [
    "connection pool exhausted causing errors",
    "it started after the timeout change deployed",
  ]);
});

test("conversations.replies throws: postmortemFacts receives humans: null", async () => {
  const h = harness({ incidentId: 7, repliesThrows: "missing_scope" });
  await h.run({ channel: "C1", ts: "100.9", thread_ts: "100.0", user: "U1" });

  assert.equal(h.calls.facts.length, 1);
  assert.equal(h.calls.facts[0].humans, null);
});
